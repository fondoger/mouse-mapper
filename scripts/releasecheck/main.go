// releasecheck verifies MyGo release completeness and the update signatures
// before CI makes a staged release visible to installed applications.
package main

import (
	"bytes"
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"time"
)

const allTargets = "windows-amd64,windows-arm64,darwin-amd64,darwin-arm64,darwin-universal"

var versionPattern = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$`)
var repositoryPattern = regexp.MustCompile(`^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$`)

type configuration struct {
	Name    string `json:"name"`
	Version string `json:"version"`
	MacOS   struct {
		MinimumSystemVersion string `json:"minimumSystemVersion"`
	} `json:"macos"`
	Updates struct {
		GitHub     string `json:"github"`
		PublicKey  string `json:"publicKey"`
		PrivateKey string `json:"privateKey"`
		TagPrefix  string `json:"tagPrefix"`
	} `json:"updates"`
}

type signedFile struct {
	URL       string `json:"url"`
	Size      int64  `json:"size"`
	Signature string `json:"signature"`
}

type manifest struct {
	Version string `json:"version"`
	Date    string `json:"date"`
	signedFile
	Deltas []struct {
		From string `json:"from"`
		signedFile
	} `json:"deltas"`
}

type asset struct {
	Name   string
	Digest []byte
}

func main() {
	configPath := flag.String("config", "mygo.json", "MyGo configuration file")
	tag := flag.String("tag", "", "require this release tag")
	repository := flag.String("repository", "", "require this GitHub owner/repository")
	requireKey := flag.Bool("require-key", false, "require a matching MYGO_UPDATER_PRIVATE_KEY without printing it")
	directory := flag.String("dir", "", "verify flat downloaded assets or nested MyGo build output")
	targetList := flag.String("targets", allTargets, "comma-separated update targets to verify")
	checksums := flag.String("checksums", "", "write SHA256SUMS for verified assets to this file")
	flag.Parse()
	if err := run(*configPath, *tag, *repository, *requireKey, *directory, *targetList, *checksums); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(configPath, tag, repository string, requireKey bool, directory, targetList, checksums string) error {
	data, err := os.ReadFile(configPath)
	if err != nil {
		return err
	}
	var config configuration
	if err := json.Unmarshal(data, &config); err != nil {
		return err
	}
	key, err := validateConfig(config, tag, repository)
	if err != nil {
		return err
	}
	if requireKey {
		if err := validatePrivateKey(key, os.Getenv("MYGO_UPDATER_PRIVATE_KEY")); err != nil {
			return err
		}
	}
	if directory == "" {
		if checksums != "" {
			return errors.New("-checksums requires -dir")
		}
		fmt.Println("Release configuration verified.")
		return nil
	}
	assets, err := verifyAssets(config, key, directory, strings.Split(targetList, ","))
	if err != nil {
		return err
	}
	if checksums != "" {
		if err := writeChecksums(checksums, assets); err != nil {
			return err
		}
	}
	fmt.Printf("Verified %d installers, update manifests and signed update files.\n", len(assets))
	return nil
}

func validateConfig(config configuration, tag, repository string) (ed25519.PublicKey, error) {
	if config.Name == "" || strings.ContainsAny(config.Name, `/\:*?"<>|`+"\r\n") {
		return nil, errors.New("name must be a safe package filename")
	}
	if !versionPattern.MatchString(config.Version) {
		return nil, errors.New("version must be a semantic version without a leading v")
	}
	if _, err := parseMacVersion(config.MacOS.MinimumSystemVersion); err != nil {
		return nil, fmt.Errorf("macos.minimumSystemVersion: %w", err)
	}
	if config.Updates.TagPrefix != "v" {
		return nil, errors.New("updates.tagPrefix must be v for this release workflow")
	}
	if tag != "" && tag != "v"+config.Version {
		return nil, errors.New("the release tag must match the version in mygo.json")
	}
	if !repositoryPattern.MatchString(config.Updates.GitHub) || (repository != "" && repository != config.Updates.GitHub) {
		return nil, errors.New("updates.github must match this GitHub repository")
	}
	if config.Updates.PrivateKey != "" {
		return nil, errors.New("do not commit an updates.privateKey path; use the CI secret")
	}
	key, err := base64.StdEncoding.DecodeString(strings.TrimSpace(config.Updates.PublicKey))
	if err != nil || len(key) != ed25519.PublicKeySize {
		return nil, errors.New("updates.publicKey must be a base64 Ed25519 public key")
	}
	return ed25519.PublicKey(key), nil
}

func validatePrivateKey(public ed25519.PublicKey, text string) error {
	key, err := base64.StdEncoding.DecodeString(strings.TrimSpace(text))
	if err != nil || len(key) != ed25519.PrivateKeySize {
		return errors.New("set MYGO_UPDATER_PRIVATE_KEY to the private key generated by mygo keygen")
	}
	derived := ed25519.NewKeyFromSeed(key[:ed25519.SeedSize])
	if !bytes.Equal(key, derived) || !bytes.Equal(public, derived[ed25519.SeedSize:]) {
		return errors.New("MYGO_UPDATER_PRIVATE_KEY does not match updates.publicKey")
	}
	return nil
}

func verifyAssets(config configuration, key ed25519.PublicKey, directory string, targets []string) ([]asset, error) {
	var assets []asset
	seen := map[string]bool{}
	for _, target := range targets {
		if !slices.Contains(strings.Split(allTargets, ","), target) || seen[target] {
			return nil, fmt.Errorf("unsupported or duplicate update target %q", target)
		}
		seen[target] = true
		name := "update-" + target + ".json"
		folder := directory
		if _, err := os.Stat(filepath.Join(folder, name)); errors.Is(err, os.ErrNotExist) {
			folder = filepath.Join(directory, target)
		}
		data, err := readManifest(filepath.Join(folder, name))
		if err != nil {
			return nil, err
		}
		var update manifest
		if err := json.Unmarshal(data, &update); err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		if update.Version != config.Version {
			return nil, fmt.Errorf("%s has the wrong version", name)
		}
		if _, err := time.Parse(time.RFC3339, update.Date); err != nil {
			return nil, fmt.Errorf("%s has no valid build timestamp", name)
		}
		archive, err := verifySignedFile(config, key, folder, update.signedFile, "-"+config.Version+"-"+target+".tar.gz")
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		if strings.HasPrefix(target, "darwin-") {
			if err := verifyMacMinimum(config, filepath.Join(folder, archive.Name)); err != nil {
				return nil, fmt.Errorf("%s: %w", name, err)
			}
		}
		manifestDigest := sha256.Sum256(data)
		assets = append(assets, asset{Name: name, Digest: manifestDigest[:]}, archive)
		for _, delta := range update.Deltas {
			if !versionPattern.MatchString(delta.From) {
				return nil, fmt.Errorf("%s contains an invalid delta version", name)
			}
			file, err := verifySignedFile(config, key, folder, delta.signedFile, "-"+delta.From+"-to-"+config.Version+"-"+target+".delta")
			if err != nil {
				return nil, fmt.Errorf("%s delta: %w", name, err)
			}
			assets = append(assets, file)
		}
		installer, err := findInstaller(folder, installerName(config, target))
		if err != nil {
			return nil, err
		}
		digest, size, err := hashFile(filepath.Join(folder, installer))
		if err != nil {
			return nil, fmt.Errorf("installer %s: %w", installer, err)
		}
		if size == 0 {
			return nil, fmt.Errorf("installer %s is empty", installer)
		}
		assets = append(assets, asset{Name: installer, Digest: digest})
	}
	if len(assets) == 0 {
		return nil, errors.New("no update targets requested")
	}
	slices.SortFunc(assets, func(a, b asset) int { return strings.Compare(a.Name, b.Name) })
	for i := 1; i < len(assets); i++ {
		if assets[i-1].Name == assets[i].Name {
			return nil, fmt.Errorf("duplicate release filename %s", assets[i].Name)
		}
	}
	return assets, nil
}

func readManifest(path string) ([]byte, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	const limit = 1 << 20
	data, err := io.ReadAll(io.LimitReader(f, limit+1))
	if len(data) > limit {
		return nil, errors.New("update manifest exceeds 1 MiB")
	}
	return data, err
}

func verifySignedFile(config configuration, key ed25519.PublicKey, folder string, file signedFile, suffix string) (asset, error) {
	u, err := url.Parse(file.URL)
	if err != nil {
		return asset{}, errors.New("invalid update URL")
	}
	prefix := "/" + config.Updates.GitHub + "/releases/download/v" + config.Version + "/"
	name := strings.TrimPrefix(u.Path, prefix)
	if u.Scheme != "https" || u.Host != "github.com" || u.User != nil || u.RawQuery != "" || u.Fragment != "" ||
		!strings.HasPrefix(u.Path, prefix) || strings.ContainsAny(name, "/\\\r\n") || !strings.HasSuffix(name, suffix) {
		return asset{}, errors.New("update URL must name this version and target in this repository")
	}
	digest, size, err := hashFile(filepath.Join(folder, name))
	if err != nil {
		return asset{}, err
	}
	if file.Size <= 0 || file.Size != size {
		return asset{}, fmt.Errorf("size does not match for %s", name)
	}
	// MyGo v0.5.5 signs the archive's SHA-256 digest, not the manifest JSON.
	signature, err := base64.StdEncoding.DecodeString(file.Signature)
	if err != nil || !ed25519.Verify(key, digest, signature) {
		return asset{}, fmt.Errorf("invalid update signature for %s", name)
	}
	return asset{Name: name, Digest: digest}, nil
}

func installerName(config configuration, target string) string {
	osName, architecture, _ := strings.Cut(target, "-")
	if osName == "windows" {
		return fmt.Sprintf("%s Setup %s %s.exe", config.Name, config.Version, architecture)
	}
	if architecture == "universal" {
		return fmt.Sprintf("%s %s.dmg", config.Name, config.Version)
	}
	return fmt.Sprintf("%s %s %s.dmg", config.Name, config.Version, architecture)
}

func findInstaller(directory, localName string) (string, error) {
	// GitHub replaces spaces with dots in uploaded release asset names. Accept
	// only the two exact names, never a loose glob or an ambiguous pair.
	names := []string{localName}
	if uploadedName := strings.ReplaceAll(localName, " ", "."); uploadedName != localName {
		names = append(names, uploadedName)
	}
	var found string
	for _, name := range names {
		_, err := os.Lstat(filepath.Join(directory, name))
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", err
		}
		if found != "" {
			return "", fmt.Errorf("ambiguous installer: both %s and %s are present", found, name)
		}
		found = name
	}
	if found == "" {
		return "", fmt.Errorf("missing installer %s (or its GitHub space-to-dot filename)", localName)
	}
	return found, nil
}

func hashFile(path string) ([]byte, int64, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, 0, err
	}
	if !info.Mode().IsRegular() {
		return nil, 0, errors.New("release assets must be regular files")
	}
	f, err := os.Open(path)
	if err != nil {
		return nil, 0, err
	}
	defer f.Close()
	hash := sha256.New()
	size, err := io.Copy(hash, f)
	return hash.Sum(nil), size, err
}

func writeChecksums(path string, assets []asset) error {
	var text strings.Builder
	for _, file := range assets {
		fmt.Fprintf(&text, "%s  %s\n", hex.EncodeToString(file.Digest), file.Name)
	}
	return os.WriteFile(path, []byte(text.String()), 0o644)
}
